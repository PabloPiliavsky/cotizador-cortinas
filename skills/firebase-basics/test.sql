SELECT 1
FROM ORDER_RELEASE ORR,
     ORDER_RELEASE CURR,
     ORDER_RELEASE_STATUS ORS
WHERE CURR.ORDER_RELEASE_GID = ?
  AND ORR.ORDER_RELEASE_GID <> CURR.ORDER_RELEASE_GID
  AND ORR.DEST_LOCATION_GID = CURR.DEST_LOCATION_GID
  AND TRUNC(
        UTC.GET_LOCAL_DATE(
            ORR.EARLY_PICKUP_DATE,
            ORR.SOURCE_LOCATION_GID
        )
      ) =
      TRUNC(
        UTC.GET_LOCAL_DATE(
            CURR.EARLY_PICKUP_DATE,
            CURR.SOURCE_LOCATION_GID
        )
      )
  AND ORS.ORDER_RELEASE_GID = ORR.ORDER_RELEASE_GID
  AND ORS.STATUS_TYPE_GID = 'SLGA.PLANNING'
  AND ORS.STATUS_VALUE_GID = in('SLGA.PLANNING_PLANNED - FINAL','SLGA.PLANNING_EXECUTED - FINAL')
  AND ROWNUM = 1


